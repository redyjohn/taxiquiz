// 生成題庫檔案路徑的輔助函數
export function getQuestionBankPath(category, type, region = "") {
  // 映射中文分類到英文路徑
  const categoryMap = {
    地理: "Geography",
    法規: "Regulations"
  }
  
  const typeMap = {
    選擇題: "MultipleChoice",
    是非題: "TrueOrFalse"
  }
  
  const regionMap = {
    臺北市: "Taipei",
    新北市: "NewTaipei",
    基隆市: "Keelung",
    桃園市: "Taoyuan",
    新竹市: "HsinchuCity",
    新竹縣: "Hsinchu",
    苗栗縣: "Miaoli",
    台中: "Taichung",
    彰化: "Changhua",
    南投: "Nantou",
    雲林縣: "Yunlin",
    嘉義市: "ChiayiCity",
    嘉義縣: "Chiayi",
    台南市: "Tainan",
    高雄市: "Kaohsiung",
    屏東縣: "Pingtung",
    台東縣: "Taitung",
    花蓮縣: "Hualien",
    宜蘭縣: "Yilan",
    澎湖縣: "Penghu",
    金門縣: "Kinmen",
    連江縣: "Lienchiang"
  }
  
  const categoryPath = categoryMap[category] || category
  const typePath = typeMap[type] || type
  
  if (region) {
    const regionFileName = type === "選擇題" 
      ? `${regionMap[region] || region}Multiple.json`
      : `${regionMap[region] || region}TF.json`
    return `/data/${categoryPath}/${typePath}/${regionFileName}`
  }
  
  // 法規類別
  const fileName = type === "選擇題" 
    ? "ReguMultChoice.json"
    : "ReguTuOrFalse.json"
  return `/data/${categoryPath}/${fileName}`
}

// 生成題庫檔案的唯一識別碼
export function getQuestionBankId(category, type, region = "") {
  return `${category}_${type}_${region || "all"}`
}

